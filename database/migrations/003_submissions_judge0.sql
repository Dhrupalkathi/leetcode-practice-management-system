SELECT setval(
  pg_get_serial_sequence('public.submission', 'submission_id'),
  COALESCE((SELECT MAX(submission_id) FROM public.submission), 0) + 1,
  FALSE
);

CREATE TABLE IF NOT EXISTS public.submission_test_result (
  submission_id    INTEGER NOT NULL
                   REFERENCES public.submission(submission_id)
                   ON UPDATE CASCADE ON DELETE CASCADE,
  test_case_number INTEGER NOT NULL CHECK (test_case_number > 0),
  status           VARCHAR(24) NOT NULL
                   CHECK (status IN (
                     'ACCEPTED','WRONG_ANSWER','COMPILATION_ERROR',
                     'TIME_LIMIT_EXCEEDED','MEMORY_LIMIT_EXCEEDED',
                     'RUNTIME_ERROR','SYSTEM_ERROR'
                   )),
  time_taken_ms    INTEGER NOT NULL DEFAULT 0 CHECK (time_taken_ms >= 0),
  memory_used_kb   INTEGER NOT NULL DEFAULT 0 CHECK (memory_used_kb >= 0),
  error_message    TEXT,
  PRIMARY KEY (submission_id, test_case_number)
);

CREATE INDEX IF NOT EXISTS submission_user_submitted_idx
