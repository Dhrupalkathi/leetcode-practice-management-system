-- Migration 004: connect contest submissions to their contest.
-- Existing contest and submission data is preserved.
BEGIN;

-- Explicit contest scoring defaults: 100 points per solved problem and 5 minutes
-- of penalty per wrong full submission made before the first accepted solution.
ALTER TABLE public.contest
  ADD COLUMN IF NOT EXISTS points_per_problem INTEGER NOT NULL DEFAULT 100
    CHECK (points_per_problem > 0),
  ADD COLUMN IF NOT EXISTS wrong_attempt_penalty_minutes INTEGER NOT NULL DEFAULT 5
    CHECK (wrong_attempt_penalty_minutes >= 0),
  ADD COLUMN IF NOT EXISTS time_penalty_enabled BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE public.contest
  ADD COLUMN IF NOT EXISTS created_by_user_id INTEGER;

ALTER TABLE public.contest
  ALTER COLUMN organizer_id DROP NOT NULL;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'contest'
      AND column_name = 'contest_id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE public.contest
      ALTER COLUMN contest_id
      ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END;
$migration$;

SELECT setval(
  pg_get_serial_sequence('public.contest', 'contest_id'),
  COALESCE((SELECT MAX(contest_id) FROM public.contest), 0) + 1,
  FALSE
);

ALTER TABLE public.contest
  ADD CONSTRAINT fk_contest_created_by_user
  FOREIGN KEY (created_by_user_id)
  REFERENCES public.users(user_id)
  ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.submission
  ADD COLUMN IF NOT EXISTS contest_id INTEGER
  REFERENCES public.contest(contest_id)
  ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.submission
  ADD CONSTRAINT ck_submission_one_context
  CHECK (contest_id IS NULL OR assessment_id IS NULL);

CREATE INDEX IF NOT EXISTS submission_contest_user_idx
  ON public.submission (contest_id, user_id, submitted_at DESC)
  WHERE contest_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS contest_start_end_idx
  ON public.contest (start_time, end_time);

COMMIT;
