-- Migration 004: contest lifecycle, scoring configuration and contest submissions.
-- Additive migration; preserves all existing contests, registrations and submissions.
BEGIN;

ALTER TABLE public.contest
  ADD COLUMN IF NOT EXISTS points_per_problem INTEGER NOT NULL DEFAULT 100
    CHECK (points_per_problem > 0),
  ADD COLUMN IF NOT EXISTS wrong_attempt_penalty_minutes INTEGER NOT NULL DEFAULT 5
    CHECK (wrong_attempt_penalty_minutes >= 0),
  ADD COLUMN IF NOT EXISTS time_penalty_enabled BOOLEAN NOT NULL DEFAULT TRUE;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='contest'
      AND column_name='contest_id' AND is_identity='YES'
  ) THEN
    ALTER TABLE public.contest
      ALTER COLUMN contest_id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END;
$migration$;

SELECT setval(
  pg_get_serial_sequence('public.contest','contest_id'),
  COALESCE((SELECT MAX(contest_id) FROM public.contest),0)+1,
  FALSE
);

ALTER TABLE public.submission
  ADD COLUMN IF NOT EXISTS contest_id INTEGER
    REFERENCES public.contest(contest_id)
    ON UPDATE CASCADE ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS submission_contest_user_problem_idx
  ON public.submission (contest_id, user_id, problem_id, submitted_at)
  WHERE contest_id IS NOT NULL;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname='ck_submission_single_context'
      AND conrelid='public.submission'::regclass
  ) THEN
    ALTER TABLE public.submission
      ADD CONSTRAINT ck_submission_single_context
      CHECK (NOT (assessment_id IS NOT NULL AND contest_id IS NOT NULL));
  END IF;
END;
$migration$;

COMMIT;
