-- Migration 006: identity generation for self-service Learner account registration.
-- Existing user IDs and role assignments are preserved.
BEGIN;

DO $migration$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='public' AND table_name='users'
      AND column_name='user_id' AND is_identity='YES'
  ) THEN
    ALTER TABLE public.users
      ALTER COLUMN user_id
      ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END;
$migration$;

SELECT setval(
  pg_get_serial_sequence('public.users','user_id'),
  COALESCE((SELECT MAX(user_id) FROM public.users),0)+1,
  FALSE
);

COMMIT;
