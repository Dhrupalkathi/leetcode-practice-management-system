-- Additive only; all existing records and role assignments are retained.
BEGIN;

CREATE TABLE IF NOT EXISTS public.notification (
  notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL
    REFERENCES public.users(user_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  notification_type VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  message TEXT NOT NULL,
  entity_type VARCHAR(40),
  entity_id VARCHAR(80),
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS notification_user_unread_date_idx
  ON public.notification(user_id,is_read,created_at DESC,notification_id DESC);

COMMIT;
