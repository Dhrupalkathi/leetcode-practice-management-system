-- Migration 010: general-purpose question types and learner-authored questions.
-- Additive only: existing coding problems, submissions and test cases are retained.
BEGIN;

ALTER TABLE public.problem
  ADD COLUMN IF NOT EXISTS question_type VARCHAR(24) NOT NULL DEFAULT 'CODING'
    CHECK (question_type IN ('CODING','MCQ_SINGLE','MCQ_MULTI','TRUE_FALSE','SHORT_ANSWER','FILL_BLANK','SQL')),
  ADD COLUMN IF NOT EXISTS question_config JSONB NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS submitted_by_user_id INTEGER REFERENCES public.users(user_id) ON DELETE SET NULL;

-- Preserve the actual author separately from the legacy Organizer ownership field.
-- Non-Organizer authors can therefore submit questions without being assigned a fake owner.
ALTER TABLE public.problem ALTER COLUMN created_by DROP NOT NULL;
UPDATE public.problem
SET submitted_by_user_id=created_by
WHERE submitted_by_user_id IS NULL AND created_by IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.problem_answer_key (
  problem_id INTEGER PRIMARY KEY REFERENCES public.problem(problem_id) ON DELETE CASCADE,
  answer_key JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.question_attempt (
  question_attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  problem_id INTEGER NOT NULL REFERENCES public.problem(problem_id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
  answer JSONB NOT NULL,
  is_correct BOOLEAN,
  review_status VARCHAR(20) NOT NULL DEFAULT 'AUTO_GRADED'
    CHECK (review_status IN ('AUTO_GRADED','PENDING_REVIEW','REVIEWED')),
  feedback TEXT,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS question_attempt_user_problem_idx
  ON public.question_attempt(user_id,problem_id,submitted_at DESC);

COMMIT;
